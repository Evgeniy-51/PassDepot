type Vars = Record<string, string | number>;

function format(template: string, vars?: Vars): string {
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, k: string) =>
        vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : `{${k}}`,
    );
}

